"""Regenerate FhirResourceTypeEnum in schema/data.yaml from the FHIR R4 code system.

Usage: python scripts/gen_fhir_enums.py [--source PATH_OR_URL] [--check] [SCHEMA]

Reads the R4 resource-types CodeSystem (by default from hl7.org) and rewrites the
enum's permissible values between the BEGIN and END marker comments in SCHEMA
(default schema/data.yaml). Each value gets the FHIR RDF type as its meaning and the
code's definition as its description. The abstract types Resource and DomainResource
are left out because no instance has them.

With --check, nothing is written: the script exits 1 if SCHEMA differs from what
the source would generate.
"""

import argparse
import json
import os
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = "https://hl7.org/fhir/R4/codesystem-resource-types.json"
EXPECTED = ("http://hl7.org/fhir/resource-types", "4.0.1")
ABSTRACT = {"Resource", "DomainResource"}
BEGIN = "      # BEGIN generated by scripts/gen_fhir_enums.py from the R4 resource-types code system\n"
END = "      # END generated\n"


def load(source):
    if source.startswith(("http://", "https://")):
        with urllib.request.urlopen(source, timeout=60) as response:
            return json.load(response)
    with open(source) as f:
        return json.load(f)


def concepts(code_system):
    """All concepts of the code system, depth first."""
    stack = list(reversed(code_system.get("concept", [])))
    while stack:
        concept = stack.pop()
        yield concept
        stack.extend(reversed(concept.get("concept", [])))


def generate(code_system):
    found = (code_system.get("url"), code_system.get("version"))
    if found != EXPECTED:
        sys.exit(f"expected the {EXPECTED[0]} code system, version {EXPECTED[1]}; got {found}")
    lines = []
    for concept in sorted(concepts(code_system), key=lambda c: c["code"]):
        code = concept["code"]
        if code in ABSTRACT:
            continue
        # A JSON string is a valid YAML scalar and survives any punctuation.
        definition = json.dumps(" ".join(concept.get("definition", "").split()), ensure_ascii=False)
        lines.append(f"      {code}:\n        meaning: fhir:{code}\n        description: {definition}\n")
    return "".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("schema", nargs="?", default=os.path.join(ROOT, "schema", "data.yaml"))
    parser.add_argument("--source", default=SOURCE, help="path or URL of the R4 resource-types CodeSystem JSON")
    parser.add_argument("--check", action="store_true", help="report whether the schema is up to date; write nothing")
    args = parser.parse_args()

    text = open(args.schema).read()
    if text.count(BEGIN) != 1 or text.count(END) != 1 or text.index(BEGIN) > text.index(END):
        sys.exit(f"{args.schema}: expected one BEGIN and one END marker, in that order")
    head, rest = text.split(BEGIN)
    _, tail = rest.split(END)
    values = generate(load(args.source))
    new = head + BEGIN + values + END + tail

    if args.check:
        current = rest.split(END)[0]
        print(f"{'up to date' if new == text else 'OUT OF DATE'}: {values.count(chr(10)) // 3} values"
              f" generated, {current.count(chr(10)) // 3} in schema")
        sys.exit(0 if new == text else 1)
    if new != text:
        with open(args.schema, "w") as f:
            f.write(new)
    print(f"wrote {values.count(chr(10)) // 3} values to {args.schema}")


if __name__ == "__main__":
    main()
