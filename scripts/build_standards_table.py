"""Write standards_table.md from src/data/standards_registry.yaml.

The table lists every standard in the registry with its release version and
date, its purpose (the first of its notes) and its selection status. Status
labels come from SelectionStatusEnum in schema/standards.yaml.

Usage (from the repository root):
    python scripts/build_standards_table.py          # rewrite standards_table.md
    python scripts/build_standards_table.py --check  # exit 1 if it is out of date
"""
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "src/data/standards_registry.yaml"
SCHEMA = ROOT / "schema/standards.yaml"
OUTPUT = ROOT / "standards_table.md"


def enum_titles(schema, name):
    values = schema["enums"][name]["permissible_values"]
    return {key: (pv or {}).get("title", key) for key, pv in values.items()}


def cell(text):
    return " ".join(str(text).split()).replace("|", "\\|") if text else ""


def version(s):
    """Release version followed by its date, unless the version already shows it."""
    v, d = cell(s.get("releaseVersion")), cell(s.get("releaseDate"))
    if v and d and d not in v:
        return f"{v} ({d})"
    return v or d


def purpose(s):
    notes = s.get("notes") or []
    return cell(notes[0]) if notes else ""


def build():
    schema = yaml.safe_load(SCHEMA.read_text(encoding="utf-8"))
    standards = yaml.safe_load(REGISTRY.read_text(encoding="utf-8"))["standards"]
    statuses = enum_titles(schema, "SelectionStatusEnum")

    for s in standards:
        status = s.get("selectionStatus")
        if status and status not in statuses:
            sys.exit(f"{s['id']}: unknown selectionStatus value {status!r}")

    header = ["Standard", "Version (release date)", "Purpose", "Status"]
    rows = [header, ["---"] * len(header)]
    for s in standards:
        rows.append([
            f"{cell(s['name'])} ({cell(s['abbreviation'])})",
            version(s),
            purpose(s),
            cell(statuses.get(s.get("selectionStatus"), "")),
        ])

    counts = {
        label: sum(s.get("selectionStatus") == key for s in standards)
        for key, label in statuses.items()
    }
    undecided = sum(not s.get("selectionStatus") for s in standards)
    summary = ", ".join(f"{n} {label.lower()}" for label, n in counts.items())
    if undecided:
        summary += f", {undecided} not yet decided"

    lines = [
        "# Standards",
        "",
        "<!-- Generated by scripts/build_standards_table.py from",
        "     src/data/standards_registry.yaml. Do not edit by hand. -->",
        "",
        f"{len(standards)} standards: {summary}.",
        "",
        *("| " + " | ".join(r) + " |" for r in rows),
        "",
    ]
    return "\n".join(lines)


def main():
    text = build()
    if "--check" in sys.argv[1:]:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            sys.exit(
                f"{OUTPUT.name} is out of date. "
                "Run: python scripts/build_standards_table.py"
            )
        return
    OUTPUT.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
